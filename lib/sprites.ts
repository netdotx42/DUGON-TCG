/**
 * Original 16x16 pixel-art sprites for DUGON TCG.
 * Legend: "#" = bone white, "+" = ash grey, "r" = blood red accent, "." = empty.
 * Sprites listed with `mirror: true` store only the left 8 columns; the right half is mirrored.
 */
export type Sprite = { rows: string[]; mirror?: boolean };

export function expandSprite(s: Sprite): string[] {
  if (!s.mirror) return s.rows;
  return s.rows.map((r) => r + r.split("").reverse().join(""));
}

